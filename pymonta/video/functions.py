"""
Video composition and silence detection utilities built on FFmpeg.

This module provides highlevel functions to:
- Detect silence intervals in a video file.
- Retrieve video duration.
- Compose video and audio streams with custom filters (e.g., overlays, mixing).
- Bake filters results.
- Render texts and pillow images.

It relies on the `pymonta.video.classes` module for `Filter`, `Media`, and `Pipe`
abstractions, and uses `ffmpeg.asyncio` for asynchronous processing.
"""

import asyncio
import hashlib
import logging
import re
import subprocess
from collections.abc import Sequence
from itertools import count
from pathlib import Path

from ffmpeg.asyncio import FFmpeg
from ffmpeg.progress import Progress
from PIL import Image, ImageDraw, ImageFont

from pymonta.video.filters import (
    Filter,
    Media,
    Pipe,
)

LOGGER = logging.getLogger(__name__)


async def detect_silence_fragments(
    video_path: str,
    silence_threshold: int = -40,
    min_duration: int = 5,
) -> list[tuple[float, float]]:
    """Detect silent intervals in a video file using FFmpeg's silencedetect filter.

    The function runs FFmpeg with `silencedetect` and parses the generated metadata
    file to extract silence start and end times.

    Args:
        video_path: Path to the input video file.
        silence_threshold: Noise level in dB (e.g., -40). Values below this are
            considered silence.
        min_duration: Minimum silence duration in seconds to report.

    Returns:
        A list of (start, end) tuples, where start and end are in seconds.

    Raises:
        FileNotFoundError: If the video file does not exist (FFmpeg will raise).
        RuntimeError: If FFmpeg execution fails.

    Note:
        The metadata is written to `silence_metadata.txt` in the current working
        directory and is parsed by `_parse_silence_metadata`.
    """
    ffmpeg = (
        FFmpeg()
        .input(video_path)
        .output(
            "-",
            af=f"silencedetect=noise={silence_threshold}dB:d={min_duration},ametadata=mode=print:file=silence_metadata.txt",
            f="null",
            vn=None,
        )
    )
    await ffmpeg.execute()
    return _parse_silence_metadata("silence_metadata.txt")


def _parse_silence_metadata(filepath: str) -> list[tuple[float, float]]:
    """Parse FFmpeg's ametadata output to extract silence intervals.

    The metadata file is generated by the `ametadata` filter with `silencedetect`.
    Each silence block appears as a `silence_start` line followed later by a
    `silence_end` line.

    Args:
        filepath: Path to the metadata file (e.g., "silence_metadata.txt").

    Returns:
        A list of (start, end) tuples with times in seconds.

    Raises:
        FileNotFoundError: If the metadata file does not exist.
    """
    with open(filepath, "r") as f:
        lines = f.readlines()

    silences = []
    current_start = None

    for line in lines:
        start_match = re.search(r"silence_start=([\d.]+)", line)
        if start_match:
            current_start = float(start_match.group(1))
        end_match = re.search(r"silence_end=([\d.]+)", line)
        if end_match and current_start is not None:
            end = float(end_match.group(1))
            silences.append((current_start, end))
            current_start = None

    return silences


def get_duration(video_path: str) -> int:
    """Retrieve the duration of a video in whole seconds using FFprobe.

    Args:
        video_path: Path to the video file.

    Returns:
        Duration in seconds (integer).
    """
    res = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_entries",
            "format=duration",
            "-of",
            "default=noprint_wrappers=1:nokey=1",
            video_path,
        ],
        check=True,
        capture_output=True,
    )
    return round(float(res.stdout.decode("utf-8")))


def build_pipelines(filters: Sequence[Filter]) -> tuple[Pipe, Pipe]:
    vout = Pipe("vout")
    aout = Pipe("aout")

    # build the filter graph (reverse order to chain correctly)
    LOGGER.debug(f"Recieved filtres: {[type(f).__name__ for f in filters]}")
    for filter in reversed(filters):
        if filter.stream_type == "audio":
            aout = aout.join(Pipe("0:a", filter))
            continue
        if filter.stream_type == "video":
            vout = vout.join(Pipe("0:v", filter))
            continue
        LOGGER.warning(
            f"Undefined filter type!! {filter}, {filter.stream_type}. Please use correct decorators for own filters!"
        )
    LOGGER.debug(
        f"Built pipeline:\n-VIDEO:{[type(f).__name__ for f in vout.get_all_filters()]}\n-AUDIO:{[type(f).__name__ for f in aout.get_all_filters()]}"
    )
    return (vout, aout)


def compose(
    video_path: str, output_path: str, filters: Sequence[Filter], **ffmpeg_output_flags
) -> FFmpeg:
    """Compose a video with custom audio/video filters and output to a new file.

    This is the main composition function. It builds an FFmpeg command pipeline by:
    1. Adding the input video as stream `0:v` and `0:a`.
    2. Registering any additional media files (via `Media` filters) as inputs.
    3. Constructing a filter complex that chains all video filters into a `vout`
       pipe and all audio filters into an `aout` pipe.
    4. Mapping the final outputs to `[vout]` and `[aout]` (or falling back to
       `0:v`/`0:a` if no filters were applied).
    5. Setting the audio codec to `aac` if any audio filter is used, otherwise `copy`.

    The function attaches a progress callback that logs frame, fps, and output size.

    Args:
        video_path: Path to the main input video file.
        output_path: Destination path for the output file. Must not already exist.
        video_filters: Sequence of filters (e.g., images, text) that operate
            on video streams. The order determines the filter chain.
        audio_filters: Sequence of filters (e.g., volume, music) for audio streams.
            The order determines the filter chain.
        **ffmpeg_output_flags: Additional keyword arguments passed directly to
            FFmpeg's `output()` method (e.g., `crf`, `bitrate`).

    Returns:
        An `FFmpeg` instance with the composed pipeline. The caller can further
        customise it (e.g., add event handlers) and must call `execute()` to start
        the process.

    Raises:
        RuntimeError: If the output file already exists.
        TypeError: If filters are not of the expected type.

    Note:
        - The main video stream is automatically assigned stream index `0`.
        - Additional media files (created via `Media` filters) get unique IDs
          starting from 1.
        - The filter order matters.
    """

    # Used for correct automatic ID assignment for additional Media instances.
    # Starts from 1 because the main video feed has ID 0.
    _ids = count(1)

    if Path(output_path).exists():
        raise RuntimeError(
            "Output file already exists! Handle it manually. Halting video composing."
        )
    LOGGER.info(f"Starting composition process for {video_path}.")
    ffmpeg = FFmpeg().input(video_path)

    # First pass: add all external media as inputs and assign IDs
    for filter in filters:
        if isinstance(filter, Media):
            ffmpeg.input(filter.path)
            LOGGER.debug(f"Input file: {filter.path}")
            filter.set_id(next(_ids))

    vout, aout = build_pipelines(filters)

    audio_changed = len(aout.get_all_filters()) > 0
    video_changed = len(vout.get_all_filters()) > 0

    acodec = "aac" if audio_changed else "copy"
    astream = "[aout]" if audio_changed else "0:a"
    vstream = "[vout]" if video_changed else "0:v"

    filter_complex = f"{vout.compile_filter()}{aout.compile_filter()}"

    LOGGER.debug(
        f"filter: {filter_complex}\n- video_output:{vstream}\n- audio_output:{astream}, audio_codec:{acodec}"
    )

    ffmpeg = ffmpeg.output(
        output_path,
        acodec=acodec,
        filter_complex=filter_complex,
        map=[vstream, astream],
        **ffmpeg_output_flags,
    )

    @ffmpeg.on("progress")
    def on_progress(progress: Progress):
        LOGGER.info(
            f"Working on {progress.frame} frame, current fps = {progress.fps}, output size: ~{progress.size / 1024 / 1024}MB"
        )

    return ffmpeg


def render_text(
    text: str,
    font_path: str | None = None,
    font_size: int = 34,
    color: str = "white",
    bg_color: tuple[int, int, int, int] = (0, 0, 0, 0),  # прозрачный по умолчанию
    align: str = "center",
    wraplength: int = 32,
) -> str:
    """
    Render text to a PNG image with transparent background and caching.

    This function creates an image containing the specified text, sized exactly
    to fit the text (with small padding). Images are cached in a `texts/`
    subdirectory under the project path, using a hash of the text and styling
    parameters. Subsequent calls with the same parameters return the cached
    image path instantly.

    Args:
        text: The text to render. Can contain `\\n` for manual line breaks.
        font_path: Path to a TrueType font file (.ttf). If `None`, uses
            the bundled DejaVuSans font (assumed to be available in the
            development environment).
        font_size: Font size in points (default: 34).
        color: Text color (any format accepted by Pillow, e.g., "white",
            "#FF0000", (255, 0, 0)). Default: "white".
        bg_color: Background color as RGBA tuple. Default: (0, 0, 0, 0) —
            fully transparent.
        align: Text alignment within the image: "left", "center", or "right".
            Default: "center".
        wraplength: Maximum number of characters per line before automatic
            wrapping. Default: 32.

    Returns:
        Absolute path to the generated (or cached) PNG image file.

    Note:
        - Manual newlines (`\\n`) are preserved and override automatic wrapping.
        - The image size is computed based on the rendered text dimensions
          plus 10 pixels of padding on each side.
        - The cache key includes: text, font_size, bg_color, color, align, font_path and wraplength
    """
    m = hashlib.sha1()
    unique_text_desc = (
        f"{text}{font_size}{bg_color}{color}{align}{font_path}{wraplength}"
    )
    m.update(unique_text_desc.encode())
    hash = m.hexdigest()
    proj_path = Path().cwd()
    output_path = proj_path / "texts" / (hash + ".png")
    output_path.parent.mkdir(exist_ok=True, parents=True)

    if output_path.exists():
        LOGGER.debug(f"Cache hit of text image: {output_path}")
        return str(output_path)

    font = ImageFont.truetype(
        font_path or "Pillow/Tests/fonts/DejaVuSans.ttf", font_size
    )

    # Wrap long lines
    if len(text) > wraplength:
        text = text.replace("\n", "@@ ")  # preserve manual breaks
        words = text.split()
        wrapped_lines = []
        line_sum = 0
        for word in words:
            if "@@" in word:  # preserve manual breaks
                word = word.replace("@@", "")
                wrapped_lines.append(f"{word}\n")
                line_sum = 0
                continue
            if len(word) + line_sum >= wraplength:
                wrapped_lines.append("\n")
                line_sum = 0
            line_sum += len(word)
            wrapped_lines.append(word)
        text = " ".join(wrapped_lines)

    dummy_img = Image.new("RGBA", (1, 1))
    draw = ImageDraw.Draw(dummy_img)

    # Вычисляем bounding box текста
    bbox = draw.textbbox((0, 0), text, font=font, align=align)
    text_width = bbox[2] - bbox[0]
    text_height = bbox[3] - bbox[1]

    # Добавляем отступы
    img_width = text_width + 2 * 10
    img_height = text_height + 2 * 10

    size = (int(img_width), int(img_height))

    img = Image.new("RGBA", size, bg_color)
    draw = ImageDraw.Draw(img)
    draw.text((size[0] // 2, size[1] // 2), text, color, font, align=align, anchor="mm")
    img.save(output_path)
    return str(output_path)


def digest_pillow(
    pillow_image: Image.Image,
) -> str:
    """
    Function for custom pillow images support.

    Supports chaining with `VideoOverlay()`.

    If same pillow image was given, function will return path to cached version.

    Args:
        - pillow_image: raw pil image class which you are willing to use in video

    Note:
        - sha1 used for caching.
    """
    project_path = Path.cwd()
    cache_dir = project_path / "pimgs"
    cache_dir.mkdir(parents=True, exist_ok=True)

    # Вычисляем хеш по уменьшенной копии
    thumb = pillow_image.copy()
    thumb.thumbnail((64, 64), Image.Resampling.LANCZOS)
    # Конвертируем в RGBA, чтобы избежать проблем с палитрой и режимами
    if thumb.mode not in ("RGBA", "RGB"):
        thumb = thumb.convert("RGBA")
    img_hash = hashlib.sha1(thumb.tobytes()).hexdigest()

    output_path = cache_dir / f"{img_hash}.png"

    # Если файл уже существует — возвращаем его, не пересохраняя
    if output_path.exists():
        LOGGER.debug(f"Cache hit: {output_path}")
        return str(output_path)

    pillow_image.save(output_path)
    LOGGER.info(f"Cached image: {output_path}")
    return str(output_path)


def bake_filters(input_file: str, filters: Sequence[Filter]) -> str:
    """
    Applies filters to input_file and saves baked result.

    Supports chaining with `VideoOverlay()`.

    Returns:
        - path of baked result

    Note:
        - If given same input_file and filters then previous baked result reused.
        - sha1 hashing used for path generation.
        - Runs seperate async event loop to generate video with ffmpeg! Use with caution!
    """
    unique_desk = f"{input_file}{[type(f).__name__ for f in filters]}"
    input_ext = Path(input_file).suffix
    hash = hashlib.sha1(unique_desk.encode()).hexdigest()
    save_path = Path().cwd() / "baked" / (hash + input_ext)
    if save_path.exists():
        LOGGER.debug(f"Cache hit: {save_path}")
        return str(save_path)
    LOGGER.info(
        f"Starting baking process for {input_file}.\n-extension: {input_ext}\n-unquie_hash: {hash}\n-save_path:{save_path}"
    )
    save_path.parent.mkdir(parents=True, exist_ok=True)
    bake = compose(input_file, str(save_path), filters)
    asyncio.run(bake.execute())
    return str(save_path)
