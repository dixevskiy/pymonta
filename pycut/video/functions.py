# Used for correct automatic ID assignment for additional Media instances.
# Starts from 1 because the main video feed has ID 0.
_ids = count(1)


def compose(
    video_path: str,
    output_path: str,
    video_filters: Sequence[Filter] | None,
    audio_filters: Sequence[Filter] | None,
    **ffmpeg_output_flags: Any,
) -> FFmpeg:
    """Compose a video with custom audio/video filters and output to a new file.

    This is the main composition function. It builds an FFmpeg command pipeline by:
    1. Adding the input video as stream `0:v` and `0:a`.
    2. Registering any additional media files (via `Media` filters) as inputs.
    3. Constructing a filter complex that chains all video filters into a `vout`
       pipe and all audio filters into an `aout` pipe.
    4. Mapping the final outputs to `[vout]` and `[aout]` (or falling back to
       `0:v`/`0:a` if no filters were applied).
    5. Setting the audio codec to `aac` if any audio filter is used, otherwise `copy`.

    The function attaches a progress callback that logs frame, fps, and output size.

    Args:
        video_path: Path to the main input video file.
        output_path: Destination path for the output file. Must not already exist.
        video_filters: Sequence of filters (e.g., images, text) that operate
            on video streams. The order determines the filter chain.
        audio_filters: Sequence of filters (e.g., volume, music) for audio streams.
            The order determines the filter chain.
        **ffmpeg_output_flags: Additional keyword arguments passed directly to
            FFmpeg's `output()` method (e.g., `crf`, `bitrate`).

    Returns:
        An `FFmpeg` instance with the composed pipeline. The caller can further
        customise it (e.g., add event handlers) and must call `execute()` to start
        the process.

    Raises:
        RuntimeError: If the output file already exists.
        TypeError: If filters are not of the expected type.

    Note:
        - The main video stream is automatically assigned stream index `0`.
        - Additional media files (created via `Media` filters) get unique IDs
          starting from 1.
        - The filter order matters.
    """
    if Path(output_path).exists():
        raise RuntimeError(
            "Output file already exists! Handle it manually. Halting video composing."
        )
    LOGGER.info(f"Starting composition process for {video_path}.")
    ffmpeg = FFmpeg().input(video_path)

    vout = Pipe("vout")
    aout = Pipe("aout")
    audio_changed = False
    video_changed = False

    if not video_filters:
        video_filters = []
    if not audio_filters:
        audio_filters = []

    # First pass: add all external media as inputs and assign IDs
    for filter in chain(video_filters, audio_filters):
        if isinstance(filter, Media):
            ffmpeg.input(filter.path)
            filter.set_id(next(_ids))

    # Second pass: build the filter graph (reverse order to chain correctly)
    for filter in chain(reversed(video_filters), reversed(audio_filters)):
        if filter.stream_type == "audio":
            aout = aout.join(Pipe("0:a", filter))
            audio_changed = True
        if filter.stream_type == "video":
            vout = vout.join(Pipe("0:v", filter))
            video_changed = True

    filter_complex = f"{vout.combine_filter()}{aout.combine_filter()}"

    acodec = "aac" if audio_changed else "copy"
    astream = "[aout]" if audio_changed else "0:a"
    vstream = "[vout]" if video_changed else "0:v"

    LOGGER.debug(
        f"filter: {filter_complex}\n- video_output:{vstream}\n- audio_output:{astream}, audio_codec:{acodec}"
    )

    ffmpeg = ffmpeg.output(
        output_path,
        acodec=acodec,
        filter_complex=filter_complex,
        map=[vstream, astream],
        **ffmpeg_output_flags,
    )

    @ffmpeg.on("progress")
    def on_progress(progress: Progress):
        LOGGER.info(
            f"Working on {progress.frame} frame, current fps = {progress.fps}, output size: ~{progress.size / 1024 / 1024}MB"
        )

    return ffmpeg